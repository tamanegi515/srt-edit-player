function memoryFs(initial = {}, failures = {}) {
  const files = new Map(Object.entries(initial));
  const directories = new Set([""]);
  const writes = [];
  const aborted = [];
  const removed = [];
  for (const path of files.keys()) {
    const parts = path.split("/");
    for (let i = 1; i < parts.length; i++) directories.add(parts.slice(0, i).join("/"));
  }
  const fail = (operation, path) => {
    const name = failures[`${operation}:${path}`];
    if (name) throw new DOMException(operation, name);
  };
  const missing = () => new DOMException("Missing entry", "NotFoundError");
  function directory(prefix = "") {
    const fullPath = (name) => prefix ? `${prefix}/${name}` : name;
    return {
      kind: "directory",
      name: prefix.split("/").pop() || "fixture",
      async removeEntry(name) {
        const path = fullPath(name);
        fail("remove", path);
        if (directories.has(path)) throw new DOMException("Directory not empty", "InvalidModificationError");
        if (!files.has(path)) throw missing();
        files.delete(path);
        removed.push(path);
      },
      async getDirectoryHandle(name, { create = false } = {}) {
        const path = fullPath(name);
        fail("directory", path);
        if (files.has(path)) throw new DOMException("File exists", "TypeMismatchError");
        if (!directories.has(path) && !create) throw missing();
        directories.add(path);
        return directory(path);
      },
      async getFileHandle(name, { create = false } = {}) {
        const path = fullPath(name);
        fail("handle", path);
        if (directories.has(path)) throw new DOMException("Directory exists", "TypeMismatchError");
        if (!files.has(path) && !create) throw missing();
        if (!files.has(path)) files.set(path, "");
        return {
          kind: "file",
          name,
          async getFile() {
            fail("read", path);
            const file = new File([files.get(path)], name);
            file.text = async () => { fail("text", path); return files.get(path); };
            return file;
          },
          async createWritable() {
            fail("writable", path);
            let pending = "";
            return {
              async write(text) { fail("write", path); pending = String(text); },
              async close() {
                fail("close", path);
                files.set(path, pending);
                writes.push(path);
              },
              async abort() { pending = ""; aborted.push(path); },
            };
          },
        };
      },
      async *values() {
        const prefixLength = prefix ? prefix.length + 1 : 0;
        for (const path of files.keys()) {
          if (prefix && !path.startsWith(`${prefix}/`)) continue;
          const name = path.slice(prefixLength);
          if (!name.includes("/")) yield await this.getFileHandle(name);
        }
      },
    };
  }
  return { dir: directory(), files, writes, directory, aborted, removed };
}

function srt(text = "BEFORE") {
  return `1\r\n00:00:00,000 --> 00:00:01,001\r\n${text}\r\n\r\n`;
}

function project(paths, extras = {}) {
  return {
    name: "fixture.vc_json",
    audioFilePath: "",
    scriptFiles: paths.map((filePath) => ({ filePath })),
    ...extras,
  };
}

test("persists exact SRT and JSON references across repeated project reloads", async () => {
  const paths = ["captions.srt", "a/captions.srt", "b/captions.srt", "a/captions.json", "b/captions.json"];
  const initial = Object.fromEntries(paths.map((path) => [path, path.endsWith(".json")
    ? JSON.stringify([{ start: "00:00:00,000", end: "00:00:01,001", sentences: ["BEFORE"] }])
    : srt()]));
  initial["fixture.vc_json"] = JSON.stringify(project(paths));
  const fs = memoryFs(initial);
  const [json] = await getJsonDataList(fs.dir);
  const media = await getMedia(json, fs.dir);
  for (const [i, track] of media.srt_data.entries()) {
    setSrtItemText(track.data[0], `AFTER ${i}\ninline\n\nparagraph`);
    // Deliberately leave cached strings stale: numeric editing must win on disk.
    track.data[0].endTime = 59.9996;
    expect(await saveSubtitleTrack(fs.dir, track)).toBe(true);
  }
  expect(await saveJsonFile(fs.dir, json.name, syncJsonDataFromMedia(json, media))).toBe(true);
  for (let round = 0; round < 3; round++) {
    const [reloadedJson] = await getJsonDataList(fs.dir);
    expect(reloadedJson.scriptFiles.map((item) => item.filePath)).toEqual(paths);
    const reloaded = await getMedia(reloadedJson, fs.dir);
    for (const [i, track] of reloaded.srt_data.entries()) {
      expect(track.loadStatus).toBe("loaded");
      expect(track.data[0].sentences).toEqual([`AFTER ${i}\ninline`, "paragraph"]);
      expect(track.data[0].endTime).toBe(60);
      expect(track.data[0].endTimeStr).toBe("00:01:00,000");
      expect(await saveSubtitleTrack(fs.dir, track)).toBe(true);
    }
  }
  expect([...fs.files.keys()].sort()).toEqual(Object.keys(initial).sort());
});

test("new-track create-only preserves unreferenced JSON and SRT including empty files", async () => {
  const initial = { "other.json": '{"private":"untouched"}', "srt/other.srt": srt("untouched"), "empty.json": "" };
  const fs = memoryFs(initial);
  const data = [createBlankSubtitleClip(2)];
  for (const path of Object.keys(initial)) expect(await createSubtitleFile(fs.dir, path, data)).toBe(false);
  expect(Object.fromEntries(fs.files)).toEqual(initial);
  expect(fs.writes).toEqual([]);
  expect(await createSubtitleFile(fs.dir, "srt/new.srt", data)).toBe(true);
  expect(parseSrt(fs.files.get("srt/new.srt"))[0].endTime).toBe(2);
  expect(await createSubtitleFile(fs.dir, "new.json", data)).toBe(true);
  expect(JSON.parse(fs.files.get("new.json"))[0].end).toBe("00:00:02,000");
});

test("concurrent create calls with distinct handles cannot overwrite the first result", async () => {
  const fs = memoryFs();
  const first = [{ ...createBlankSubtitleClip(1), text: "first" }];
  const second = [{ ...createBlankSubtitleClip(2), text: "second" }];
  const results = await Promise.all([
    createSubtitleFile(fs.dir, "srt/same.srt", first),
    createSubtitleFile(fs.directory(), "srt\\same.srt", second),
  ]);
  expect(results).toEqual([true, false]);
  expect(fs.writes).toEqual(["srt/same.srt"]);
  expect(fs.files.get("srt/same.srt")).toContain("first");
  expect(fs.files.get("srt/same.srt")).not.toContain("second");
});

test("failed reads and parses cannot overwrite sources or create missing references", async () => {
  const initial = {
    "bad.json": "{broken", "shape.json": "{}", "null.json": "null",
    "row.json": '[{"start":"bad","end":"bad","sentences":[]}]',
    "bad.srt": "not a subtitle", "denied.json": "[]", "text.json": "[]",
    "empty.json": "[]", "empty.srt": "",
  };
  const fs = memoryFs(initial, { "read:denied.json": "NotAllowedError", "text:text.json": "NotReadableError" });
  const paths = [...Object.keys(initial), "missing.json", "gone/missing.srt"];
  const media = await getMedia(project(paths, { imageSrtPath: "missing-image.srt" }), fs.dir);
  for (const track of media.srt_data) {
    if (["empty.json", "empty.srt"].includes(track.file_path)) {
      expect(track.loadStatus).toBe("loaded");
      expect(track.loadError).toBeNull();
      expect(track.data).toEqual([]);
    } else {
      expect(track.loadStatus).toBe("error");
      expect(track.loadError).toBeTruthy();
      expect(await saveSubtitleTrack(fs.dir, track)).toBe(false);
      expect(await saveSubtitleFile(fs.dir, track.file_path, [], { loadStatus: track.loadStatus })).toBe(false);
    }
  }
  expect(Object.fromEntries(fs.files)).toEqual(initial);
  expect(fs.writes).toEqual([]);
});

test("late candidate load failures release audio resources before rethrowing", async () => {
  const fs = memoryFs({ "sample.mp3": "fixture" });
  const OriginalAudio = globalThis.Audio;
  const originalCreate = URL.createObjectURL;
  const originalRevoke = URL.revokeObjectURL;
  const created = [];
  const revoked = [];
  const audioInstances = [];
  globalThis.Audio = class {
    constructor(src) {
      this.src = src;
      this.duration = 1;
      audioInstances.push(this);
      setTimeout(() => this.onloadedmetadata(), 0);
    }
    pause() { this.paused = true; }
    removeAttribute(name) { if (name === "src") this.src = null; }
    load() { this.released = true; }
  };
  URL.createObjectURL = (file) => { const url = originalCreate(file); created.push(url); return url; };
  URL.revokeObjectURL = (url) => { revoked.push(url); originalRevoke(url); };
  try {
    for (const extras of [{ imageFilePath: 123 }, { scriptFiles: [{ filePath: "", inlineData: [null] }] }]) {
      await expect(getMedia(project([], { audioFilePath: "sample.mp3", ...extras }), fs.dir)).rejects.toThrow();
    }
    expect(revoked).toEqual(created);
    expect(created).toHaveLength(2);
    expect(audioInstances.every((audio) => audio.paused && audio.released && audio.src === null)).toBe(true);
  } finally {
    if (OriginalAudio === undefined) delete globalThis.Audio;
    else globalThis.Audio = OriginalAudio;
    URL.createObjectURL = originalCreate;
    URL.revokeObjectURL = originalRevoke;
  }
});

