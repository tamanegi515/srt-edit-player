  image.data[1].startTime = 1.999;
  expect(await saveSubtitleTrack(fs.dir, image)).toBe(true);
  expect(await saveJsonFile(fs.dir, json.name, syncJsonDataFromMedia(json, media))).toBe(true);
  const [saved] = await getJsonDataList(fs.dir);
  const reloaded = await getMedia(saved, fs.dir);
