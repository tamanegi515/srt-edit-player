test("millisecond conversion and repeated SRT roundtrips preserve boundary values", () => {
  for (const milliseconds of [0, 1, 999, 1001, 1007, 59999, 60001, 3599999, 3600001, 86400001]) {
    let seconds = milliseconds / 1000;
    for (let i = 0; i < 10; i++) {
      const text = convSecToStr(seconds);
      seconds = convStrToSec(text);
      expect(Math.round(seconds * 1000)).toBe(milliseconds);
      const parsed = parseSrt(combineToSRT([{ ...createBlankSubtitleClip(), endTime: seconds, text: "roundtrip" }]));
      expect(parsed[0].endTimeStr).toBe(text);
    }
  }
  expect(convSecToStr(59.9996)).toBe("00:01:00,000");
  expect(convSecToStr(3599.9996)).toBe("01:00:00,000");
});
