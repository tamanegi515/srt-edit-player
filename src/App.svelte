  function flushEditor() {
    window.dispatchEvent(new CustomEvent("srt-editor-flush"));
  }

  // @ts-ignore
  $effect(() => {
    const data = json_data;
    const directory = projectState.dirHandle;
    const token = ++mediaLoadToken;
    // json_data / dirHandle の変化だけを追跡し、media への書き戻しで再実行しないよう untrack で退避
    const prevVol  = untrack(() => mediaState.media.volume);
    const prevRate = untrack(() => mediaState.media.playbackRate);
    untrack(() => {
      flushEditor();
      if (loadedProject) rememberMedia(loadedProject, mediaState.media);
      useAudio.pause();
      loading = true;
    });
    const ready = preparedMedia;
    preparedMedia = null;
    untrack(async () => {
    try {
      const result = await (ready ?? getMedia(data, directory));
      if (token !== mediaLoadToken) {
        // 古くなった（破棄される）結果の blob URL を解放してリークを防ぐ
        if (result.audioUrl) URL.revokeObjectURL(result.audioUrl);
        const staleImage = result.image_data?.currentImage;
        if (staleImage && typeof staleImage === "string" && staleImage.startsWith("blob:")) URL.revokeObjectURL(staleImage);
        return;
      }
      useAudio.set(result.audio ?? null, result.audioUrl ?? null);
      const { audio: _ignoredAudio, audioUrl: _ignoredUrl, ...rest } = result;
      setLoadedMedia(restoreMediaDraft(data, rest));
      loadedProject = data;
      registerLoadedMedia(data, mediaState.media);
      // メディア切り替え後も音量・倍速を維持
      useAudio.setVol(prevVol);
      useAudio.setRate(prevRate);
    } catch (err) {
      if (token !== mediaLoadToken) return;
      const previousIndex = projectState.jsonDataList.indexOf(loadedProject);
      if (previousIndex >= 0) projectState.mediaIndex = previousIndex;
      showToast("メディア読み込みに失敗しました。", "error");
    } finally {
      if (token === mediaLoadToken) loading = false;
    }
    });
  });

