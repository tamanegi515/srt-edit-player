  // フォルダを読み込み、json_dataを作成
  async function handleLoad() {
    if (loading || saving || creating) return;
    flushEditor();
    loading = true;
    let candidate = null;
    try {
      const directory = await window.showDirectoryPicker();
      const permission = await directory.requestPermission({ mode: "readwrite" });
      if (permission !== "granted") {
        showToast("フォルダの書き込み権限がありません。", "error");
        return;
      }
      const result = await getJsonDataList(directory);
      candidate = result.length ? await getMedia(result[0], directory) : getDefaultMedia();
      flushEditor();
      if (hasUnsavedChanges(loadedProject, mediaState.media) &&
          !window.confirm("現在の未保存の変更を破棄して、選択したフォルダに切り替えますか？")) return;
      for (const data of result) {
        const generatedName = getAutoGeneratedVcJsonName(data);
        if (generatedName) {
          const created = [];
          try {
            for (const script of data.scriptFiles ?? []) {
              if (!Array.isArray(script.inlineData)) continue;
              if (!await createSubtitleFile(directory, script.filePath, script.inlineData)) {
                throw new Error("Initial subtitle creation failed");
              }
              created.push(script.filePath);
            }
            if (!await saveJsonFile(directory, generatedName, data)) throw new Error("Project creation failed");
          } catch (error) {
            for (const path of created) await removeCreatedSubtitleFile(directory, path);
            throw error;
          }
        }
      }
      loadedProject = null;
      preparedMedia = candidate;
      candidate = null;
      projectState.dirHandle = directory;
      projectState.folderName = directory.name;
      setProjectDataList(result);
      resetProjectSessions(projectState.jsonDataList);
    } catch (err) {
      if (err?.name !== "AbortError") showToast("フォルダ読み込みに失敗しました。現在のプロジェクトを維持します。", "error");
    } finally {
      if (candidate?.audioUrl) URL.revokeObjectURL(candidate.audioUrl);
      if (candidate?.image_data?.currentImage) URL.revokeObjectURL(candidate.image_data.currentImage);
      loading = false;
    }
  }

  async function save_VC_JSON_File() {
    if (loading || saving || creating || loadedProject !== json_data) return;
    flushEditor();
    if (projectState.dirHandle && json_data?.name && json_data.name !== "dummy") {
      saving = true;
      const project = json_data;
      const snapshot = projectSnapshot(project);
      const nameWithoutExt = mediaState.media.name.replace(/\.[^/.]+$/, "");
      const name = `${nameWithoutExt}.vc_json`;

      const dataToSave = JSON.parse(JSON.stringify(syncJsonDataFromMedia(project, mediaState.media)));
      const success = await saveJsonFile(projectState.dirHandle, name, dataToSave);
      if (success) markProjectSaved(project, snapshot);
      saving = false;
      uiState.jsonSaveStatus = success ? 1 : -1;
      showToast(success ? 'vc_json 保存完了' : 'vc_json 保存失敗', success ? 'success' : 'error');

      // 1秒後にアイコンを通常に戻す
      setTimeout(() => {
        uiState.jsonSaveStatus = 0;
      }, 2000);
    }
  }

  async function save_SRT_Files() {
    if (loading || saving || creating || loadedProject !== json_data) return;
    flushEditor();
    if (projectState.dirHandle) {
      saving = true;
      const project = json_data;
      let saved = 0;
      let failed = 0;
      const paths = new Set();
      for (const track of mediaState.media.srt_data) {
        const key = String(track.file_path ?? "").replace(/\\/g, "/").toLowerCase();
        if (paths.has(key)) continue;
        paths.add(key);
        const snapshot = trackSnapshot(track);
        if (await saveSubtitleTrack(projectState.dirHandle, { ...track, data: JSON.parse(snapshot) })) {
          markTrackSaved(project, track, snapshot);
          saved++;
        } else failed++;
      }
      saving = false;
      const success = saved > 0 && failed === 0;
      uiState.srtSaveStatus = success ? 1 : -1;
      showToast(success ? '字幕 保存完了' : `字幕 保存: ${saved}件成功 / ${failed}件失敗`, success ? 'success' : 'error');

      // 1秒後にアイコンを通常に戻す
      setTimeout(() => {
        uiState.srtSaveStatus = 0;
      }, 2000);
    }
  }

  function sanitizeTrackFileBase(name) {
    return String(name ?? "")
      .trim()
      .replace(/[\\/:*?"<>|]/g, "_")
      .replace(/^\.+/, "")
      .slice(0, 120);
  }

  function existingSubtitlePathSet() {
    return new Set((json_data?.scriptFiles ?? []).map((item) => String(item.filePath ?? item.name ?? "").toLowerCase()));
  }

  async function createSubtitleTrackFromUI() {
    if (loading || saving || creating || loadedProject !== json_data) return;
    flushEditor();
    if (!projectState.dirHandle || !json_data?.scriptFiles) {
      showToast("フォルダを読み込んでから作成してください。", "error");
      return;
    }
    const baseName = sanitizeTrackFileBase(newTrackName);
    if (!baseName) {
      showToast("字幕トラック名を入力してください。", "error");
      return;
    }
    const extension = newTrackFormat === "srt" ? "srt" : "json";
    const filePath = extension === "srt" ? `srt/${baseName}.srt` : `${baseName}.json`;
    if (existingSubtitlePathSet().has(filePath.toLowerCase())) {
      showToast("同じ字幕ファイル名が既にあります。", "error");
      return;
    }

    const id = json_data.scriptFiles.length;
    const defaultStyle = Object.keys(json_data.styles ?? {})[0] ?? "default-style-1";
    const data = [createBlankSubtitleClip(mediaState.media.duration)];
    const scriptFile = createSubtitleScriptFile({ filePath, name: filePath, defaultStyle });
    const track = createSubtitleMediaTrack({ id, name: filePath, filePath, data, defaultStyle });
    creating = true;
    const subtitleSaved = await createSubtitleFile(projectState.dirHandle, filePath, data);
    if (!subtitleSaved) {
      creating = false;
      showToast("字幕トラックを作成できません。既存ファイル名や書き込み権限を確認してください。", "error");
      return;
    }

    addSubtitleTrack(scriptFile, track);
    const addedTrack = mediaState.media.srt_data.find((item) => item.id === track.id);
    markTrackSaved(json_data, addedTrack, trackSnapshot(addedTrack));
    const snapshot = projectSnapshot(json_data);
    const vcJsonName = `${mediaState.media.name.replace(/\.[^/.]+$/, "")}.vc_json`;
    const payload = JSON.parse(JSON.stringify(syncJsonDataFromMedia(json_data, mediaState.media)));
    const vcSaved = await saveJsonFile(projectState.dirHandle, vcJsonName, payload);
    if (vcSaved) markProjectSaved(json_data, snapshot);
    creating = false;
    newTrackName = "";
    showToast(vcSaved ? "字幕トラックを作成しました。" : "字幕は作成しましたが vc_json 保存に失敗しました。", vcSaved ? "success" : "error");
  }

  function scrollEditor() {
    window.dispatchEvent(new CustomEvent("srt-editor-scroll-current", { detail: { time: json_data.seekTime } }));
  }

  function clearOverlaySelectionOutsideRibbon(event) {
    const target = event.target;
    if (target?.closest?.(".ribbonview")) return;
    if (target?.closest?.(".srt_box")) return;
    clearOverlaySelection();
    if (!target?.closest?.('[role="separator"]')) document.activeElement?.blur?.();
  }

  // ドラッグ開始
  const startDrag = (event, index) => {
    event.preventDefault();
    event.currentTarget.focus();
    dragging = true;
    startX = event.clientX;
    currentColumnIndex = index;
    startWidth = editorLayoutState.columns[index]?.width;
    const newColumns = editorLayoutState.columns.map((column) => ({ ...column }));

    const totalWidth = editorLayoutState.columns.reduce((sum, column) => sum + column.width, 0);

    // ドラッグ中の処理（newColumns はドラッグ開始時のスナップショット。
    // ライブ state を読まずスナップショットから計算することで、移動中の累積誤差を防ぐ）
    const onMouseMove = (moveEvent) => {
      if (!dragging) return;
      const diff = moveEvent.clientX - startX;

      if (currentColumnIndex === -1) {
        // プレイヤー↔エディタ全体の境界: 全列を比率で拡縮
        const scale = (totalWidth - diff) / totalWidth;
        editorLayoutState.columns = newColumns.map((column) => ({ ...column, width: Math.max(50, column.width * scale) }));
        return;
      }

      const current = currentColumnIndex;
      const prev = current - 1;
      if (prev < 0) {
        // 先頭列: 隣接列が無いので単独で拡縮
        editorLayoutState.columns = newColumns.map((column, i) =>
          i === current ? { ...column, width: Math.max(50, newColumns[current].width - diff) } : { ...column },
        );
        return;
      }

      // 隣接列との境界: prev+current の合計を保ったまま再配分（合計幅がドラッグ中に増減しない）
      const pair = newColumns[prev].width + newColumns[current].width;
      const newCurrent = Math.max(50, Math.min(newColumns[current].width - diff, pair - 50));
      editorLayoutState.columns = newColumns.map((column, i) => {
        if (i === current) return { ...column, width: newCurrent };
        if (i === prev) return { ...column, width: pair - newCurrent };
        return { ...column };
      });
    };

    // ドラッグ終了時の処理
    const stopDrag = () => {
      dragging = false;
      window.removeEventListener("mousemove", onMouseMove);
      window.removeEventListener("mouseup", stopDrag);
    };

    // イベントリスナーを追加
    window.addEventListener("mousemove", onMouseMove);
    window.addEventListener("mouseup", stopDrag);
  };

  function resizeWithKeyboard(event, index) {
    if (!["ArrowLeft", "ArrowRight"].includes(event.key)) return;
    event.preventDefault();
    const delta = (event.key === "ArrowLeft" ? 1 : -1) * (event.shiftKey ? 40 : 10);
    const columns = editorLayoutState.columns;
    if (index === -1) {
      const width = columns.reduce((sum, column) => sum + column.width, 0);
      editorLayoutState.columns = columns.map((column) => ({ ...column, width: Math.max(50, column.width * (width + delta) / width) }));
    } else {
      const amount = Math.max(50 - columns[index].width, Math.min(delta, columns[index - 1].width - 50));
      columns[index].width += amount;
      columns[index - 1].width -= amount;
    }
  }

  async function splitIntoSubtitleBox({ track, data, blockId, before, after }) {
    if (loading || saving || creating || loadedProject !== json_data) return;
    if (!mediaState.media.srt_data.includes(track) || track.loadStatus !== "loaded") return;
    flushEditor();
    const index = track.data.indexOf(data);
    if (index < 0) return;
    const script = json_data.scriptFiles[track.id];
    if (track.file_path.toLowerCase().endsWith(".json")) {
      try {
        let id;
        editClips(track, [data], () => { id = splitSubtitleBlock(data, blockId, before, after, script); });
        selectEditorClip(track.id, index, id);
        selectOverlayTrack(track.id, null, index, id);
        return { index, blockId: id };
      } catch {
        showToast("箱を分割できません。箱の数や字幕の構造を確認してください。", "error");
        return;
      }
    }

    creating = true;
    convertingTrack = true;
    let createdPath = null;
    try {
      const original = JSON.parse(trackSnapshot(track));
      const candidate = JSON.parse(JSON.stringify(original));
      const id = splitSubtitleBlock(candidate[index], blockId, before, after, script);
      const base = track.file_path.replace(/\.srt$/i, "");
      const referencedPaths = new Set(projectState.jsonDataList.flatMap((project) =>
        (project.scriptFiles ?? []).map((item) => String(item.filePath ?? "").replace(/\\/g, "/").toLowerCase())));
      let path;
      for (let suffix = 1; suffix <= 100; suffix++) {
        const proposed = `${base}.boxes${suffix === 1 ? "" : `-${suffix}`}.json`;
        if (referencedPaths.has(proposed.replace(/\\/g, "/").toLowerCase())) continue;
        try {
          await getFileFromPath(projectState.dirHandle, proposed);
        } catch (error) {
          if (error.name !== "NotFoundError") throw error;
          path = proposed;
          break;
        }
      }
      if (!path || !await createSubtitleFile(projectState.dirHandle, path, candidate)) {
        throw new Error("Subtitle JSON creation failed");
      }
      createdPath = path;
      const payload = JSON.parse(JSON.stringify(syncJsonDataFromMedia(json_data, mediaState.media)));
      payload.scriptFiles[track.id].filePath = path;
      payload.scriptFiles[track.id].name = path;
      const vcName = `${mediaState.media.name.replace(/\.[^/.]+$/, "")}.vc_json`;
      if (!await saveJsonFile(projectState.dirHandle, vcName, payload)) throw new Error("Project reference save failed");

      // Detach this JSON source from other projects that still reference the original SRT.
      const sourceData = track.data;
      track.data = original;
      forkEditorHistory(sourceData, track.data, (value) => {
        let reactiveClip = $state(value);
        return reactiveClip;
      });
      track.file_path = path;
      track.name = path;
      script.filePath = path;
      script.name = path;
      editClips(track, [track.data[index]], () => {
        const target = track.data[index];
        for (const key of ["text", "sentences", "layout", "additionalBlocks"]) {
          if (candidate[index][key] === undefined) delete target[key];
          else target[key] = candidate[index][key];
        }
      });
      markTrackSaved(json_data, track, trackSnapshot(track));
      markProjectSaved(json_data, projectSnapshot(json_data));
      createdPath = null;
      selectEditorClip(track.id, index, id);
      selectOverlayTrack(track.id, null, index, id);
      showToast(`元SRTを残し、${path} に保存しました。`);
      return { index, blockId: id };
    } catch {
      if (createdPath) await removeCreatedSubtitleFile(projectState.dirHandle, createdPath);
      showToast("箱を分割できませんでした。元の字幕と参照先を維持します。", "error");
    } finally {
      creating = false;
      convertingTrack = false;
    }
  }

  onMount(() => {
    const preventDiscard = (event) => {
      flushEditor();
      if (!hasUnsavedChanges(loadedProject, mediaState.media) && !loading && !saving && !creating) return;
      event.preventDefault();
      event.returnValue = "";
    };
    window.addEventListener("beforeunload", preventDiscard);
    return () => {
      window.removeEventListener("beforeunload", preventDiscard);
      clearTimeout(toastTimer);
    };
  });
