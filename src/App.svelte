  <label class="toggle_switch" style="margin-right: 5px;">
    <input type="checkbox" bind:checked={uiState.viewRibbon} style="visibility: hidden;" />
    <span class="toggle-slider"></span>
  </label>
  {#if uiState.viewRibbon}
    <StyleRibbon></StyleRibbon>
  {/if}

  {#if toastMessage}
    <div class="toast toast-{toastType}">{toastMessage}</div>
  {/if}
  {#if projectState.jsonDataList.length > projectState.mediaIndex && json_data?.styles}
    <table style="width: 100%; height: {tableHeight}px;" bind:this={useRefs.tableRef} cellspacing="0" cellpadding="0">
      <tbody>
        <tr>
          <!-- 🎬 左側：メディアプレイヤー -->
          <td>
            {#if mediaState.media}
              <MediaPlayer />
            {/if}
          </td>

          <!-- 🟦 リサイズバー -->
          <td style="width: 5px;">
            <div class="resizer" role="button" tabindex="-1" style="cursor: ew-resize; height: 100%;" onmousedown={(event) => startDrag(event, -1)}></div>
          </td>

          <!-- 📝 右側：編集エリア（ネストテーブル）-->
          <td style="width:{totalWidth}px; vertical-align: top;">
            <table class="srt_area" style="width: 100%; height: 100%;" cellspacing="0" cellpadding="0">
              <tbody>
                <!-- 上部操作エリア -->
                <tr>
                  <td colspan={editorLayoutState.columns.length} style="height: 30px;">
                    <button class="nmorph_button" style="margin-left:15px;" onclick={removeEditorColumn}>◀</button>
                    <span>{editorLayoutState.columns.length}</span>
                    <button class="nmorph_button" onclick={addEditorColumn}>▶</button>
                        <button class="nmorph_button" onclick={scrollEditor} title="再生位置にスクロール"> Scroll </button>
                    <input class="new-track-name" data-testid="new-subtitle-track-name" type="text" bind:value={newTrackName} placeholder="new subtitle" />
                    <select class="new-track-format" data-testid="new-subtitle-track-format" bind:value={newTrackFormat}>
                      <option value="json">json</option>
                      <option value="srt">srt</option>
                    </select>
                    <button class="nmorph_button" data-testid="create-subtitle-track" onclick={createSubtitleTrackFromUI} title="字幕トラックを作成">
                      <span class="material-symbols-outlined"> add </span>
                    </button>
                    <button class="nmorph_button" onclick={save_SRT_Files} title="字幕を保存">
                      {#if uiState.srtSaveStatus == 0}
                        <span class="material-symbols-outlined"> save_as </span>
                      {:else if uiState.srtSaveStatus > 0}
                        <span class="material-symbols-outlined"> check </span>
                      {:else}
                        <span class="material-symbols-outlined"> error </span>
                      {/if}
                    </button>
                  </td>
                </tr>

                <!-- 各列（字幕編集欄） -->
                <tr>
                  {#each editorLayoutState.columns as column, index (column.id)}
                    <td style="width: {column.width}px; position: relative; height: 100%;">
                      <div style="display: flex; height: 100%;">
                        <div class="resize-bar" role="button" tabindex="-1" onmousedown={(event) => startDrag(event, index)}></div>
                        <div style="flex-grow: 1; height: 100%;">
                          <SrtEditor bind:this={useRefs.editorRefs[index]} parents_height={tableHeight} column={column} style="height: 100%;" />
                        </div>
                      </div>
                    </td>
                  {/each}
                </tr>
              </tbody>
            </table>
          </td>
        </tr>
      </tbody>
    </table>

    {#if uiState.viewTrack}
      <TrackView></TrackView>
    {/if}
  {/if}
</main>

