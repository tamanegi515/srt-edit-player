<script>
  import StyleRibbon from "./components/Style_Ribbon.svelte";
  import MediaPlayer from "./components/Media_Player.svelte";
  import SrtEditor from "./components/Srt_Editor.svelte";
  import { onMount, untrack } from "svelte";
  import { innerHeight } from "svelte/reactivity/window";
  import {
    addEditorColumn,
    addSubtitleTrack,
    clearOverlaySelection,
    editorLayoutState,
    mediaState,
    projectState,
    removeEditorColumn,
    setLoadedMedia,
    setProjectDataList,
    uiState,
    useAudio,
    useRefs,
  } from "./lib/store.svelte";
  import {
    createBlankSubtitleClip,
    createSubtitleMediaTrack,
    createSubtitleScriptFile,
    getAutoGeneratedVcJsonName,
    getDefaultJsonData,
    getDefaultMedia,
    getJsonDataList,
    getMedia,
    saveJsonFile,
    saveSubtitleFile,
    syncJsonDataFromMedia,
  } from "./lib/data_process";
  import Track from "./components/Track.svelte";
  import TrackView from "./components/Track_View.svelte";

  let dragging = $state(false);
  let startX = $state(0);
  let startWidth = $state();

  // トースト通知
  let toastMessage = $state('');
  let toastType = $state('');
  let toastTimer;
  function showToast(message, type = 'success') {
    toastMessage = message;
    toastType = type;
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => { toastMessage = ''; }, 3000);
  }
  let json_data = $derived(projectState.jsonDataList[projectState.mediaIndex]);
  let mediaLoadToken = 0;
  let newTrackName = $state("");
  let newTrackFormat = $state("json");
  let mainRef = $state();

  // @ts-ignore
  $effect(async () => {
    const token = ++mediaLoadToken;
    // json_data / dirHandle の変化だけを追跡し、media への書き戻しで再実行しないよう untrack で退避
    const prevVol  = untrack(() => mediaState.media.volume);
    const prevRate = untrack(() => mediaState.media.playbackRate);
    try {
      const result = await getMedia(json_data, projectState.dirHandle);
      if (token !== mediaLoadToken) {
        if (result.audioUrl) URL.revokeObjectURL(result.audioUrl);
        return;
      }
      useAudio.set(result.audio ?? null, result.audioUrl ?? null);
      const { audio: _ignoredAudio, audioUrl: _ignoredUrl, ...rest } = result;
      setLoadedMedia(rest);
      useRefs.editorRefs = [];
      // メディア切り替え後も音量・倍速を維持
      useAudio.setVol(prevVol);
      useAudio.setRate(prevRate);
    } catch (err) {
      if (token !== mediaLoadToken) return;
      console.warn("メディア読み込みエラー:", err);
      useAudio.set(null);
      setLoadedMedia(getDefaultMedia());
    }
  });

  // UI部品まわりの変数
  let currentColumnIndex = $state(-1);

  const totalWidth = $derived.by(() => {
    return editorLayoutState.columns.reduce((sum, column) => sum + column.width, 0);
  });

  // trackRef のサイズ変化を ResizeObserver でリアクティブに追跡
  let trackHeight = $state(0);
  $effect(() => {
    const el = useRefs.trackRef;
    if (!el) return;
    const ro = new ResizeObserver(([entry]) => {
      trackHeight = entry.contentRect.height;
    });
    ro.observe(el);
    trackHeight = el.getBoundingClientRect().height;
    return () => ro.disconnect();
  });

  const tableHeight = $derived.by(() => {
    innerHeight.current;
    if (!mainRef || !useRefs.tableRef) return 120;
    const mainRect = mainRef.getBoundingClientRect();
    const tableRect = useRefs.tableRef.getBoundingClientRect();
    const mainStyle = getComputedStyle(mainRef);
    const paddingBottom = parseFloat(mainStyle.paddingBottom) || 0;
    const reservedTrackHeight = uiState.viewTrack
      ? Math.min(Math.max(trackHeight || 0, 70), 160)
      : 0;
    return Math.max(120, Math.floor(mainRect.bottom - tableRect.top - reservedTrackHeight - paddingBottom));
  });

  // メインモデルの監視用
  // $effect(() => {
  //   console.log("json_data_list:", $state.snapshot(json_data_list));
  //   console.log("media_index:", $state.snapshot(media_index));
  //   console.log("media:", $state.snapshot(media));
  //   console.log("style_list:", $state.snapshot(style_list));
  // });

  function stopAudio() {
    useAudio.stop();
  }

  // フォルダを読み込み、json_dataを作成
  async function handleLoad() {
    stopAudio();
    // @ts-ignore
    projectState.dirHandle = await window.showDirectoryPicker();

    // 書き込み権限をリクエスト
    const permission = await projectState.dirHandle.requestPermission({ mode: "readwrite" });

    if (permission !== "granted") {
      console.warn("書き込み権限が許可されませんでした。");
      return;
    }

    projectState.folderName = projectState.dirHandle.name;
    try {
      const result = await getJsonDataList(projectState.dirHandle);
      for (const data of result) {
        const generatedName = getAutoGeneratedVcJsonName(data);
        if (generatedName) {
          await saveJsonFile(projectState.dirHandle, generatedName, data);
        }
      }
      setProjectDataList(result);
      console.log("フォルダ読み込み完了：", result);
    } catch (err) {
      console.warn("読み込みエラー:", err);
      projectState.folderName = "";
    }
  }

  async function save_VC_JSON_File() {
    if (projectState.dirHandle && json_data?.name && json_data.name !== "dummy") {
      const nameWithoutExt = mediaState.media.name.replace(/\.[^/.]+$/, "");
      const name = `${nameWithoutExt}.vc_json`;

      const dataToSave = syncJsonDataFromMedia(json_data, mediaState.media);
      const success = await saveJsonFile(projectState.dirHandle, name, dataToSave);
      uiState.jsonSaveStatus = success ? 1 : -1;
      showToast(success ? 'vc_json 保存完了' : 'vc_json 保存失敗', success ? 'success' : 'error');

      // 1秒後にアイコンを通常に戻す
      setTimeout(() => {
        uiState.jsonSaveStatus = 0;
      }, 2000);
    }
  }

  async function save_SRT_Files() {
    let success = false;
    if (projectState.dirHandle) {
      console.log(mediaState.media);
      for (const srtfile of mediaState.media.srt_data.filter((track) => !track.isImageTrack)) {
        success = await saveSubtitleFile(projectState.dirHandle, srtfile.file_path || srtfile.name, srtfile.data);
        if (!success) break;
      }
      uiState.srtSaveStatus = success ? 1 : -1;
      showToast(success ? '字幕 保存完了' : '字幕 保存失敗', success ? 'success' : 'error');

      // 1秒後にアイコンを通常に戻す
      setTimeout(() => {
        uiState.srtSaveStatus = 0;
      }, 2000);
    }
  }

  function sanitizeTrackFileBase(name) {
    return String(name ?? "")
      .trim()
      .replace(/[\\/:*?"<>|]/g, "_")
      .replace(/^\.+/, "")
      .slice(0, 120);
  }

  function existingSubtitlePathSet() {
    return new Set((json_data?.scriptFiles ?? []).map((item) => String(item.filePath ?? item.name ?? "").toLowerCase()));
  }

  async function createSubtitleTrackFromUI() {
    if (!projectState.dirHandle || !json_data?.scriptFiles) {
      showToast("フォルダを読み込んでから作成してください。", "error");
      return;
    }
    const baseName = sanitizeTrackFileBase(newTrackName);
    if (!baseName) {
      showToast("字幕トラック名を入力してください。", "error");
      return;
    }
    const extension = newTrackFormat === "srt" ? "srt" : "json";
    const filePath = extension === "srt" ? `srt/${baseName}.srt` : `${baseName}.json`;
    if (existingSubtitlePathSet().has(filePath.toLowerCase())) {
      showToast("同じ字幕ファイル名が既にあります。", "error");
      return;
    }

    const id = json_data.scriptFiles.length;
    const defaultStyle = Object.keys(json_data.styles ?? {})[0] ?? "default-style-1";
    const data = [createBlankSubtitleClip(mediaState.media.duration)];
    const scriptFile = createSubtitleScriptFile({ filePath, name: filePath, defaultStyle });
    const track = createSubtitleMediaTrack({ id, name: filePath, filePath, data, defaultStyle });
    const subtitleSaved = await saveSubtitleFile(projectState.dirHandle, filePath, data);
    if (!subtitleSaved) {
      showToast("字幕トラック作成に失敗しました。", "error");
      return;
    }

    addSubtitleTrack(scriptFile, track);
    const vcJsonName = `${mediaState.media.name.replace(/\.[^/.]+$/, "")}.vc_json`;
    const vcSaved = await saveJsonFile(projectState.dirHandle, vcJsonName, syncJsonDataFromMedia(json_data, mediaState.media));
    newTrackName = "";
    showToast(vcSaved ? "字幕トラックを作成しました。" : "字幕は作成しましたが vc_json 保存に失敗しました。", vcSaved ? "success" : "error");
  }

  function scrollEditor() {
    for (const ref of useRefs.editorRefs) {
      console.log(ref);
      if (ref) {
        ref.scrollToIndex(json_data.seekTime);
      }
    }
  }

  function clearOverlaySelectionOutsideRibbon(event) {
    const target = event.target;
    if (target?.closest?.(".ribbonview")) return;
    if (target?.closest?.(".srt_box")) return;
    clearOverlaySelection();
    document.activeElement?.blur?.();
  }

  // ドラッグ開始
  const startDrag = (event, index) => {
    dragging = true;
    startX = event.clientX;
    currentColumnIndex = index;
    startWidth = editorLayoutState.columns[index]?.width;
    const newColumns = editorLayoutState.columns.map((column) => ({ ...column }));

    const totalWidth = editorLayoutState.columns.reduce((sum, column) => sum + column.width, 0);

    // ドラッグ中の処理
    const onMouseMove = (moveEvent) => {
      if (dragging) {
        const diff = moveEvent.clientX - startX;

        if (currentColumnIndex == -1) {
          const scale = (totalWidth - diff) / totalWidth; // 拡大なら scale > 1、縮小なら < 1
          editorLayoutState.columns = newColumns.map((column) => ({ ...column, width: Math.max(50, column.width * scale) }));
        } else {
          // 元の幅を複製してから調整

          const current = currentColumnIndex;
          const prev = current - 1;

          const newWidth = Math.max(50, startWidth - diff);
          // 現在列に delta を加える
          newColumns[current].width = newWidth;
          if (prev >= 0) {
            const delta = newWidth - editorLayoutState.columns[current].width;

            // 前の列から delta を引く
            newColumns[prev].width = Math.max(50, editorLayoutState.columns[prev].width - delta);
          }
          editorLayoutState.columns = newColumns;
        }
      }
    };

    // ドラッグ終了時の処理
    const stopDrag = () => {
      dragging = false;
      window.removeEventListener("mousemove", onMouseMove);
      window.removeEventListener("mouseup", stopDrag);
    };

    // イベントリスナーを追加
    window.addEventListener("mousemove", onMouseMove);
    window.addEventListener("mouseup", stopDrag);
  };

  onMount(() => {
    window.addEventListener("beforeunload", () => {
      useAudio.stop();
    });
  });
</script>

<main bind:this={mainRef} onmousedown={clearOverlaySelectionOutsideRibbon}>
