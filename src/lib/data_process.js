export async function saveJsonFile(dirHandle, name = "sample.vc_json", jsondata, subdir = null) {
    if (!dirHandle) return false;

    try {
        // 保存先ディレクトリの取得
        const targetDirHandle = subdir
            ? await dirHandle.getDirectoryHandle(subdir, { create: true })
            : dirHandle;

        // 書き込むファイルのハンドル
        const fileHandle = await targetDirHandle.getFileHandle(name, { create: true });
        const writable = await fileHandle.createWritable();

        // jsondata.name を name に置き換えたコピーを作成
        const nameWithoutExt = name;
        const dataToSave = {
            ...stripInlineDataFromVcJson(jsondata),
            name: nameWithoutExt,
        };

        await writable.write(JSON.stringify(dataToSave, null, 2));
        await writable.close();

        console.log(`保存完了: ${subdir ? `${subdir}/` : ""}${name}`);
        return true;
    } catch (err) {
        console.error("保存失敗:", err);
        return false;
    }
}



export async function getJsonDataList(dirHandle) {
    const result = [];
    const entries = [];
    for await (const entry of dirHandle.values()) {
        entries.push(entry);
    }
    const fileEntries = getSortedFileEntries(entries);

    let files = fileEntries.filter((entry) => entry.name.endsWith(".vc_json"));
    for (const entry of files) {
        const file = await entry.getFile();
        const text = await file.text();
        const data = getVCJsonData(text, file.name);
        result.push(data);
    }
    if (result.length) return result;

    files = fileEntries.filter((entry) => entry.name.endsWith(".voice_json"));
    for (const entry of files) {
        const file = await entry.getFile();
        const text = await file.text();
        const data = getVoiceJsonData(file.name, text);
        result.push(data);
    }

    if (result.length) return result;

    const audioEntry = fileEntries.find((entry) => hasExtension(entry.name, AUDIO_EXTENSIONS));
    const imageEntry = fileEntries.find((entry) => hasExtension(entry.name, IMAGE_EXTENSIONS));
    const jsonSubtitleEntries = fileEntries.filter((entry) => entry.name.endsWith(".json"));

    for (const entry of jsonSubtitleEntries) {
        const file = await entry.getFile();
        const text = await file.text();
        const data = getSentenceJsonData(file.name, text, {
            audioFilePath: audioEntry?.name ?? "",
            imageFilePath: imageEntry?.name ?? "",
        });
        if (data) {
            result.push(markAutoGenerated(data, getGeneratedVcJsonName(getBaseName(file.name))));
        }
    }
    if (result.length) return result;

    const srtEntries = fileEntries.filter((entry) => entry.name.endsWith(".srt"));
    if (srtEntries.length || audioEntry || imageEntry) {
        const baseName = getBaseName(audioEntry?.name ?? srtEntries[0]?.name ?? imageEntry?.name ?? dirHandle.name ?? "sample");
        const scriptFiles = srtEntries.length
            ? srtEntries.map((entry) => defaultSrtFileShape({ filePath: entry.name, name: entry.name }))
            : [defaultSrtFileShape({ filePath: getDefaultGeneratedTrackName(baseName), inlineData: [] })];

        result.push(markAutoGenerated(createProjectJsonData({
            name: baseName,
            audioFilePath: audioEntry?.name ?? "",
            imageFilePath: imageEntry?.name ?? "",
            scriptFiles,
        }), getGeneratedVcJsonName(baseName)));
    }
    return result;

}


