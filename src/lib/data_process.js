const AUTO_GENERATED_VC_JSON = Symbol("autoGeneratedVcJson");

function hasExtension(name, extensions) {
    const lower = name.toLowerCase();
    return extensions.some((ext) => lower.endsWith(ext));
}

function markAutoGenerated(data, vcJsonName) {
    Object.defineProperty(data, AUTO_GENERATED_VC_JSON, {
        value: vcJsonName,
        enumerable: false,
    });
    return data;
}

export function getAutoGeneratedVcJsonName(data) {
    return data?.[AUTO_GENERATED_VC_JSON] ?? null;
}

function getSortedFileEntries(entries) {
    return entries
        .filter((entry) => entry.kind === "file")
        .sort((a, b) => a.name.localeCompare(b.name, "ja"));
}

function getBaseName(filename) {
    return filename.replace(/\.[^/.]+$/, "");
}

function getGeneratedVcJsonName(baseName) {
    return `${baseName || "sample"}.vc_json`;
}

function getDefaultGeneratedTrackName(baseName) {
    return `${baseName || "sample"}.srt`;
}


