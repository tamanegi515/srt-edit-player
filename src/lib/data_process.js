// Serialize creates across handles so repeated clicks cannot pass the same existence check.
// File System Access has no atomic exclusive-create primitive against external writers.
let subtitleCreationQueue = Promise.resolve();
export async function createSubtitleFile(dirHandle, path, data) {
    const create = async () => {
        if (!path || !Array.isArray(data)) return false;
        try {
            return await saveTextFileByPath(dirHandle, path, serializeSubtitle(path, data), true);
        } catch {
            return false;
        }
    };
    const result = subtitleCreationQueue.then(create);
    subtitleCreationQueue = result.then(() => undefined, () => undefined);
    return result;
}

// The caller must only pass paths successfully created by its current operation.
export async function removeCreatedSubtitleFile(dirHandle, path) {
    if (!dirHandle) return false;
    try {
        const parts = getSubtitlePathParts(path);
        const name = parts.pop();
        let directory = dirHandle;
        for (const part of parts) directory = await directory.getDirectoryHandle(part);
        await directory.getFileHandle(name);
        await directory.removeEntry(name);
        return true;
    } catch {
        return false;
    }
}

function getPersistedTime(item, edge) {
    const seconds = item[`${edge}Time`] ?? convStrToSec(item[`${edge}TimeStr`]);
    if (!Number.isFinite(seconds) || seconds < 0) throw new Error("Invalid subtitle time");
    return convSecToStr(seconds);
}


export function combineToSRT(data) {
    if (data.some(hasClipBlockExtensions)) {
        throw new TypeError("SRT cannot preserve subtitle block extensions; save as JSON");
    }
    let srtText = "";
    let id = 1;
    for (const srtPart of data) {
        srtText += id + '\r\n';
        srtText += getPersistedTime(srtPart, "start") + ' --> ' + getPersistedTime(srtPart, "end");
        if (getSrtItemText(srtPart)) {
            srtText += '\r\n' + serializeSrtBodyText(srtPart);
            if (srtPart.text !== "\r\n") srtText += '\r\n\r\n';
        } else {
            srtText += '\r\n\u3000\r\n\r\n';
        }
        id++;
    }
    return srtText;
}


export function getCurrentText(data, time) {
    // data は normalizeSrtItems 済み（startTime 昇順・連続、endTime も昇順）である前提。
    // endTime 昇順を利用し「endTime >= time となる最も手前のクリップ」を二分探索で求める。
    // これは線形走査の「最初に一致したクリップを返す（継ぎ目では手前優先）」と同じ結果になり、
    // 再生中に毎フレーム呼ばれる探索を O(n) → O(log n) に下げる。
    let lo = 0;
    let hi = data.length;
    while (lo < hi) {
        const mid = (lo + hi) >> 1;
        if (data[mid].endTime >= time) hi = mid;
        else lo = mid + 1;
    }
    const entry = data[lo];
    if (entry && time >= entry.startTime && time <= entry.endTime) {
        const primaryText = getSrtItemText(entry);
        const text = primaryText.trim() ? primaryText
            : getClipBlocks(entry).slice(1).map(({ body }) => getSrtItemText(body)).find((value) => value.trim()) ?? primaryText;
        return { text, entry, index: lo };
    }
    return { text: "", entry: null, index: -1 }; // 一致なし
}




export const calculate_shadow = ({ enable, steps, offsetX, offsetY, size, color, blur }) => {
    if (!enable) return "none";
    const shadowSize = size;
    const shadowBlur = blur;
    const shadowColor = color;

    let textShadow = "none";
    if (steps == 1) {
        textShadow = `${offsetX}px ${offsetY}px ${shadowBlur}px ${shadowColor}`;
    } else {
        const outerShadows = createShadowDirections(steps).map(
            ([dx, dy]) =>
                `${offsetX + dx * shadowSize}px ${offsetY + dy * shadowSize}px ${shadowBlur}px ${shadowColor}`
        );
        textShadow = [...outerShadows].join(", ");
    }

    return textShadow;
}

const createShadowDirections = (steps, offset = 0) => {
    steps = Math.ceil(steps);
    const angleStep = (2 * Math.PI) / steps;
    return Array.from({ length: steps }, (_, i) => {
        const angle = i * angleStep + offset;
        return [Math.round(Math.cos(angle)), Math.round(Math.sin(angle))];
    });
};



export function convertToStyledSpans(defaultStyleName, text) {
    const result = [];
    const tagPattern = /<(\w+)>([\s\S]*?)<\/>/g;
    let lastIndex = 0;

    for (const match of text.matchAll(tagPattern)) {
        const [fullMatch, styleName, content] = match;
        const start = match.index;

        // タグの前の通常テキスト
        if (start > lastIndex) {
            const normal = text.slice(lastIndex, start);
            result.push({ style: defaultStyleName, text: normal });
        }

        // タグ部分
        result.push({ style: styleName, text: content });

        lastIndex = start + fullMatch.length;
    }

    // 残り
    if (lastIndex < text.length) {
        result.push({ style: defaultStyleName, text: text.slice(lastIndex) });
    }

    return result;
}





function normalizeSrtItems(srtItems) {
    const sorted = [...srtItems].sort((a, b) => a.startTime - b.startTime);
    const normalized = [];

    for (let i = 0; i < sorted.length; i++) {
        const curr = { ...sorted[i] };
        validateClipBlocks(curr);
        const prev = normalized[normalized.length - 1];

        if (!prev) {
            if (curr.startTime > 0) {
                normalized.push({
                    startTime: 0,
                    endTime: curr.startTime,
                    startTimeStr: "00:00:00,000",
                    endTimeStr: convSecToStr(curr.startTime),
                    text: "　",
                    ref: {}
                });
            }
        } else {
            // 被り解消
            if (curr.startTime < prev.endTime) {
                prev.endTime = curr.startTime;
                prev.endTimeStr = convSecToStr(prev.endTime);
            }

            // 空白時間 → text: "" を挿入
            if (curr.startTime > prev.endTime) {
                normalized.push({
                    startTime: prev.endTime,
                    endTime: curr.startTime,
                    startTimeStr: convSecToStr(prev.endTime),
                    endTimeStr: convSecToStr(curr.startTime),
                    text: "　",
                    ref: {}
                });
            }
        }

        // 時間逆転防止（安全対策）
        if (curr.endTime < curr.startTime) {
            curr.endTime = curr.startTime;
        }

        // str更新
        curr.startTimeStr = convSecToStr(curr.startTime);
        curr.endTimeStr = convSecToStr(curr.endTime);

        // "　" 連続 → 結合処理
        if (
            prev &&
            !hasClipBlockExtensions(prev) &&
            !hasClipBlockExtensions(curr) &&
            isOnlyFullWidthSpace(prev.text) &&
            isOnlyFullWidthSpace(curr.text)
        ) {
            // prevのendを伸ばす
            prev.endTime = curr.endTime;
            prev.endTimeStr = convSecToStr(curr.endTime);
        } else {
            normalized.push(curr);
        }
    }

    return normalized;
}

function isOnlyFullWidthSpace(text) {
    return typeof text === "string" && text.trim() === "" && /　/.test(text);
}
