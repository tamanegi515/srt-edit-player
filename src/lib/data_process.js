export function getVoiceJsonData(filename, text) {
    const raw = JSON.parse(text);
    const result = getDefaultJsonData();

    result.name = filename;
    result.seekTime = raw.seekTime || 0;
    result.audioFilePath = raw.audioFile || '';
    result.imageSrtPath = raw.imageSRT || '';
    result.scriptFiles = [];
    // @ts-ignore
    result.styles = {};

    // 各SRTファイルを処理
    raw.srtFiles?.forEach((srt, index) => {
        const styleKey = `default-style-${index + 1}`;

        // スタイル部分を切り出し
        const {
            max_width, max_height, isVertical,
            textAlignSelect, verticalAlignSelect,
            font, fontSize, textColor,
            letter_space, line_space,
            isBold, isItalic,
            outline1, outline2, shadow,
            ...layoutProps
        } = srt;

        const fixColorObject = (obj) => {
            const { color, opacity, ...rest } = obj;
            return {
                ...rest,
                color: COLOR.mergeColorAndOpacity({ color, opacity:1-opacity })
            };
        };
        
        const outline1Fixed = fixColorObject(outline1);
        const outline2Fixed = fixColorObject({ ...outline2 });
        const shadowFixed = fixColorObject({
            ...shadow,
            steps: 1,
            offsetX: 0,
            offsetY: 0
        });

        const align = textAlignSelect == 1 ? "left" : textAlignSelect == 2 ? "center" : "right";
        // scriptFilesに1つ追加（配列形式）
        result.scriptFiles.push({
            ...layoutProps,
            maxWidth: max_width,
            maxHeight: max_height,
            defaultStyle: styleKey,
            textAlign: align,
            textRotate: isVertical ? "vertical-rl" : "horizontal-tb",

        });

        const fontStyle = isItalic ? "italic" : "normal";
        const fontWeight = isBold ? "bold" : "normal";

        // stylesにスタイル登録
        result.styles[styleKey] = {
            font, fontSize, textColor,
            letterSpace: letter_space,
            lineSpace: line_space,
            fontWeight, fontStyle,
            outline1:outline1Fixed, 
            outline2:outline2Fixed, 
            shadow:shadowFixed
        };
    });

    normalizeStyleColors(result.styles);
    return ensureProjectHasEditableTrack(result);
}

function joinSentences(sentences) {
    return (sentences ?? [])
        .map((sentence) => String(sentence ?? "").trim())
        .filter((sentence) => sentence.length > 0)
        .join("\r\n");
}

function parseSentenceJsonSubtitle(text, allowUnrelatedJson = false) {
    const raw = JSON.parse(text);
    const rows = Array.isArray(raw) ? raw : raw?.items;
    if (!Array.isArray(rows)) {
        if (allowUnrelatedJson) return null;
        throw new Error("Invalid subtitle JSON structure");
    }
    if (rows.some((row) => !row || (Object.prototype.hasOwnProperty.call(row, "sentences")
        ? !Array.isArray(row.sentences) || row.sentences.some((sentence) => typeof sentence !== "string")
        : typeof row.text !== "string"))) {
        throw new Error("Invalid subtitle sentences");
    }
    return rows.map((row) => ({
        startTimeStr: row.start,
        endTimeStr: row.end,
        startTime: convStrToSec(row.start),
        endTime: convStrToSec(row.end),
        ...(Array.isArray(row.sentences) ? {
            sentences: row.sentences.map((sentence) => normalizeInlineNewlines(sentence).trim()).filter((sentence) => sentence.length > 0),
            text: joinSentences(row.sentences),
        } : { text: normalizeInlineNewlines(row.text) }),
        ...copyClipBlockExtensions(row),
        ref: {},
    }));
}

