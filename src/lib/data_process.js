// SRTファイルをパースしてデータ配列に変換する関数
export function parseSrt(srt_text) {
    if (srt_text === null) return [];

    //srtファイルの構造の記述
    //  "通し番号"
    //  "時間 --> 時間" 
    //  "文章 + 改行2回(もしくは末尾)"
    const blockPattern = /(?:^|\r?\n\r?\n)(\d+)\r?\n([\d:,]+)\s-{2}>\s([\d:,]+)\r?\n([\s\S]*?)(?=\r?\n\r?\n\d+\r?\n|$)/g;

    const srtList = [];
    let parsedEnd = 0;
    for (const match of srt_text.matchAll(blockPattern)) {
        if (srt_text.slice(parsedEnd, match.index).trim()) throw new Error("Invalid SRT block");
        srtList.push(parseSrtBlock({
            id: match[1],
            start: match[2],
            end: match[3],
            body: match[4],
        }));
        parsedEnd = match.index + match[0].length;
    }
    if (srt_text.slice(parsedEnd).trim()) throw new Error("Invalid SRT data");
    if (!srtList.length) return [];
    return srtList ? normalizeSrtItems(srtList) : [];
};

/**
 * SRT データの最後のクリップの endTime が duration より短い場合に duration まで引き伸ばす
 * @param {Array} srtData
 * @param {number} duration 秒
 */
export function extendLastClipToDuration(srtData, duration) {
    if (!srtData || srtData.length === 0 || !duration) return;
    const last = srtData[srtData.length - 1];
    if (last.endTime < duration) {
        last.endTime = duration;
        last.endTimeStr = convSecToStr(duration);
    }
}


// SRTファイルのブロックをデータに変換する関数
export function parseSrtBlock(part) {
    let id;
    let start;
    let end;
    let text;
    if (typeof part === "string") {
        const match = part.match(/^(\d+)\r?\n([\d:,]+)\s-{2}>\s([\d:,]+)\r?\n?([\s\S]*)$/);
        if (!match) return null;
        id = parseInt(match[1]);
        start = match[2];
        end = match[3];
        text = match[4] ?? "";
    } else {
        id = parseInt(part.id);
        start = part.start;
        end = part.end;
        text = part.body ?? "";
    }
    const parsedBody = parseSrtBodyText(text);

    const entry = {
        startTimeStr: start,
        endTimeStr: end,
        startTime: convStrToSec(start),
        endTime: convStrToSec(end),
        text: parsedBody.text,
        ...(parsedBody.sentences.length > 1 ? { sentences: parsedBody.sentences } : {}),
        ref: {}
    };
    return entry;
}





