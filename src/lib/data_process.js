// SRTファイルをパースしてデータ配列に変換する関数
export function parseSrt(srt_text) {
    if (srt_text === null) return [];

    //srtファイルの構造の記述
    //  "通し番号"
    //  "時間 --> 時間" 
    //  "文章 + 改行2回(もしくは末尾)"
    const blockPattern = /(?:^|\r?\n\r?\n)(\d+)\r?\n([\d:,]+)\s-{2}>\s([\d:,]+)\r?\n([\s\S]*?)(?=\r?\n\r?\n\d+\r?\n|$)/g;

    const srtList = [];
    for (const match of srt_text.matchAll(blockPattern)) {
        srtList.push(parseSrtBlock({
            id: match[1],
            start: match[2],
            end: match[3],
            body: match[4],
        }));
    }
    if (!srtList.length) return [];
    return srtList ? normalizeSrtItems(srtList) : [];
};

/**
 * SRT データの最後のクリップの endTime が duration より短い場合に duration まで引き伸ばす
 * @param {Array} srtData
 * @param {number} duration 秒
 */
export function extendLastClipToDuration(srtData, duration) {
    if (!srtData || srtData.length === 0 || !duration) return;
    const last = srtData[srtData.length - 1];
    if (last.endTime < duration) {
        last.endTime = duration;
        last.endTimeStr = convSecToStr(duration);
    }
}


// SRTファイルのブロックをデータに変換する関数
export function parseSrtBlock(part) {
    let id;
    let start;
    let end;
    let text;
    if (typeof part === "string") {
        const match = part.match(/^(\d+)\r?\n([\d:,]+)\s-{2}>\s([\d:,]+)\r?\n?([\s\S]*)$/);
        if (!match) return null;
        id = parseInt(match[1]);
        start = match[2];
        end = match[3];
        text = match[4] ?? "";
    } else {
        id = parseInt(part.id);
        start = part.start;
        end = part.end;
        text = part.body ?? "";
    }
    const parsedBody = parseSrtBodyText(text);

    const entry = {
        startTimeStr: start,
        endTimeStr: end,
        startTime: convStrToSec(start),
        endTime: convStrToSec(end),
        text: parsedBody.text,
        ...(parsedBody.sentences.length > 1 ? { sentences: parsedBody.sentences } : {}),
        ref: {}
    };
    return entry;
}





export async function saveSrtFile(dirHandle, name, data, subdir = null) {
    if (!dirHandle) return false;

    try {
        // 保存先ディレクトリの取得
        const targetDirHandle = subdir
            ? await dirHandle.getDirectoryHandle(subdir, { create: true })
            : dirHandle;

        // 書き込むファイルのハンドル
        const fileHandle = await targetDirHandle.getFileHandle(name, { create: true });
        const writable = await fileHandle.createWritable();

        // jsondata.name を name に置き換えたコピーを作成
        const nameWithoutExt = name;

        await writable.write(combineToSRT(data));
        await writable.close();

        console.log(`保存完了: ${subdir ? `${subdir}/` : ""}${name}`);
        return true;
    } catch (err) {
        console.error("保存失敗:", err);
        return false;
    }
}

function serializeSentenceJsonSubtitle(data) {
    return JSON.stringify((data ?? []).map((item) => {
        const sentences = Array.isArray(item?.sentences) && item.sentences.length
            ? item.sentences.map((sentence) => normalizeInlineNewlines(sentence).trim()).filter(Boolean)
            : splitTextToSentences(getSrtItemText(item));
        return {
            start: item.startTimeStr ?? convSecToStr(item.startTime ?? 0),
            end: item.endTimeStr ?? convSecToStr(item.endTime ?? 0),
            sentences,
        };
    }), null, 2);
}

async function saveTextFileByPath(dirHandle, path, text, subdir = null) {
    if (!dirHandle) return false;
    try {
        let targetDirHandle = subdir
            ? await dirHandle.getDirectoryHandle(subdir, { create: true })
            : dirHandle;
        const normalizedPath = String(path || "").replace(/\\/g, "/");
        const parts = normalizedPath.split("/").filter(Boolean);
        const fileName = parts.pop();
        if (!fileName) return false;
        for (const part of parts) {
            targetDirHandle = await targetDirHandle.getDirectoryHandle(part, { create: true });
        }
        const fileHandle = await targetDirHandle.getFileHandle(fileName, { create: true });
        const writable = await fileHandle.createWritable();
        await writable.write(text);
        await writable.close();
        console.log(`保存完了: ${subdir ? `${subdir}/` : ""}${normalizedPath}`);
        return true;
    } catch (err) {
        console.error("保存失敗", err);
        return false;
    }
}

export async function saveSubtitleFile(dirHandle, path, data, options = {}) {
    const normalizedPath = String(path || "subtitle.srt").replace(/\\/g, "/");
    if (normalizedPath.toLowerCase().endsWith(".json")) {
        return saveTextFileByPath(dirHandle, normalizedPath, serializeSentenceJsonSubtitle(data));
    }

    const base = normalizedPath.split("/").pop().replace(/\.[^/.]+$/, "") || "subtitle";
    const srtName = `${base}.srt`;
    return saveSrtFile(dirHandle, srtName, data, options.srtSubdir ?? "srt");
}


export function combineToSRT(data) {
    let srtText = "";
    let id = 1;
    for (const srtPart of data) {
        srtText += id + '\r\n';
        srtText += srtPart.startTimeStr + ' --> ' + srtPart.endTimeStr;
        if (getSrtItemText(srtPart)) {
            srtText += '\r\n' + serializeSrtBodyText(srtPart);
            if (srtPart.text !== "\r\n") srtText += '\r\n\r\n';
        } else {
            srtText += '\r\n\u3000\r\n\r\n';
        }
        id++;
    }
    return srtText;
}


export function getCurrentText(data, time) {
    for (let i = 0; i < data.length; i++) {
        const entry = data[i];
        if (time >= entry.startTime && time <= entry.endTime) {
            return { text: getSrtItemText(entry), entry, index: i };
        }
    }
    return { text: "", entry: null, index: -1 }; // 一致なし
}




export const calculate_shadow = ({ enable, steps, offsetX, offsetY, size, color, blur }) => {
    if (!enable) return "none";
    const shadowSize = size;
    const shadowBlur = blur;
    const shadowColor = color;

    let textShadow = "none";
    if (steps == 1) {
        textShadow = `${offsetX}px ${offsetY}px ${shadowBlur}px ${shadowColor}`;
    } else {
        const outerShadows = createShadowDirections(steps).map(
            ([dx, dy]) =>
                `${offsetX + dx * shadowSize}px ${offsetY + dy * shadowSize}px ${shadowBlur}px ${shadowColor}`
        );
        textShadow = [...outerShadows].join(", ");
    }

    return textShadow;
}

const createShadowDirections = (steps, offset = 0) => {
    steps = Math.ceil(steps);
    const angleStep = (2 * Math.PI) / steps;
    return Array.from({ length: steps }, (_, i) => {
        const angle = i * angleStep + offset;
        return [Math.round(Math.cos(angle)), Math.round(Math.sin(angle))];
    });
};



export function convertToStyledSpans(defaultStyleName, text) {
    const result = [];
    const tagPattern = /<(\w+)>([\s\S]*?)<\/>/g;
    let lastIndex = 0;

    for (const match of text.matchAll(tagPattern)) {
        const [fullMatch, styleName, content] = match;
        const start = match.index;

        // タグの前の通常テキスト
        if (start > lastIndex) {
            const normal = text.slice(lastIndex, start);
            result.push({ style: defaultStyleName, text: normal });
        }

        // タグ部分
        result.push({ style: styleName, text: content });

        lastIndex = start + fullMatch.length;
    }

    // 残り
    if (lastIndex < text.length) {
        result.push({ style: defaultStyleName, text: text.slice(lastIndex) });
    }

    return result;
}





function normalizeSrtItems(srtItems) {
    const sorted = [...srtItems].sort((a, b) => a.startTime - b.startTime);
    const normalized = [];

    for (let i = 0; i < sorted.length; i++) {
        const curr = { ...sorted[i] };
        const prev = normalized[normalized.length - 1];

        if (!prev) {
            if (curr.startTime > 0) {
                normalized.push({
                    startTime: 0,
                    endTime: curr.startTime,
                    startTimeStr: "00:00:00,000",
                    endTimeStr: convSecToStr(curr.startTime),
                    text: "　",
                    ref: {}
                });
            }
        } else {
            // 被り解消
            if (curr.startTime < prev.endTime) {
                prev.endTime = curr.startTime;
                prev.endTimeStr = convSecToStr(prev.endTime);
            }

            // 空白時間 → text: "" を挿入
            if (curr.startTime > prev.endTime) {
                normalized.push({
                    startTime: prev.endTime,
                    endTime: curr.startTime,
                    startTimeStr: convSecToStr(prev.endTime),
                    endTimeStr: convSecToStr(curr.startTime),
                    text: "　",
                    ref: {}
                });
            }
        }

        // 時間逆転防止（安全対策）
        if (curr.endTime < curr.startTime) {
            curr.endTime = curr.startTime;
        }

        // str更新
        curr.startTimeStr = convSecToStr(curr.startTime);
        curr.endTimeStr = convSecToStr(curr.endTime);

        // "　" 連続 → 結合処理
        if (
            prev &&
            isOnlyFullWidthSpace(prev.text) &&
            isOnlyFullWidthSpace(curr.text)
        ) {
            // prevのendを伸ばす
            prev.endTime = curr.endTime;
            prev.endTimeStr = convSecToStr(curr.endTime);
        } else {
            normalized.push(curr);
        }
    }

    return normalized;
}

function isOnlyFullWidthSpace(text) {
    return typeof text === "string" && text.trim() === "" && /　/.test(text);
}
