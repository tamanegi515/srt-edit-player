function cloneSrtData(data) {
    return (data ?? []).map((item) => ({ ...item, ref: item.ref ?? {} }));
}

function normalizeInlineNewlines(text) {
    return String(text ?? "").replace(/\r(?!\n)/g, "\n");
}

function splitTextToSentences(text) {
    const lines = normalizeInlineNewlines(text).replace(/\r\n/g, "\n").split("\n");
    const sentences = [];
    let current = [];

    for (const line of lines) {
        if (isParagraphSeparatorLine(line)) {
            if (current.length) {
                sentences.push(current.join("\n"));
                current = [];
            }
            continue;
        }
        current.push(line);
    }
    if (current.length) sentences.push(current.join("\n"));

    return sentences
        .map((sentence) => sentence.trim())
        .filter((sentence) => sentence.length > 0);
}

function joinSentencesWithParagraphBreak(sentences) {
    return (sentences ?? []).map((sentence) => normalizeInlineNewlines(sentence)).join("\r\n");
}

function isParagraphSeparatorLine(line) {
    return String(line ?? "").trim() === "" || /^[　]+$/.test(String(line ?? ""));
}

function isSrtParagraphSeparatorLine(line) {
    return isParagraphSeparatorLine(line);
}

function parseSrtBodyText(body) {
    const lines = String(body ?? "").replace(/\r\n|\r|\n/g, "\n").replace(/\n+$/g, "").split("\n");
    const sentences = [];
    let current = [];

    for (const line of lines) {
        if (isSrtParagraphSeparatorLine(line)) {
            if (current.length) {
                sentences.push(current.join("\n"));
                current = [];
            }
            continue;
        }
        current.push(line);
    }
    if (current.length) sentences.push(current.join("\n"));

    const text = sentences.length ? joinSentencesWithParagraphBreak(sentences) : "";
    return { text, sentences };
}

function serializeSrtBodyText(item) {
    const sentences = Array.isArray(item?.sentences) && item.sentences.length
        ? item.sentences
        : splitTextToSentences(getSrtItemText(item));
    return sentences
        .map((sentence) => normalizeInlineNewlines(sentence).replace(/\r\n/g, "\n").replace(/\n/g, "\r\n"))
        .join("\r\n　\r\n");
}

export function getSrtItemText(item) {
    if (!item) return "";
    if (Array.isArray(item.sentences)) {
        return joinSentencesWithParagraphBreak(item.sentences);
    }
    return normalizeInlineNewlines(item.text ?? "");
}

export function setSrtItemText(item, text) {
    if (!item) return;
    const normalized = normalizeInlineNewlines(text);
    const sentences = splitTextToSentences(normalized);
    if (sentences.length > 1) {
        item.sentences = sentences;
        item.text = joinSentencesWithParagraphBreak(sentences);
    } else {
        delete item.sentences;
        item.text = sentences[0] ?? normalized;
    }
}

export function setSrtItemSentence(item, index, text) {
    if (!item || !Array.isArray(item.sentences)) return;
    item.sentences[index] = normalizeInlineNewlines(text);
    item.text = joinSentencesWithParagraphBreak(item.sentences);
}

function getDurationFromSrtData(tracks) {
    return Math.max(0, ...tracks.flatMap((track) => (track.data ?? []).map((item) => item.endTime || 0)));
}

function serializeJsonSrtItem(item) {
    const sentences = Array.isArray(item?.sentences) && item.sentences.length
        ? item.sentences.map((sentence) => normalizeInlineNewlines(sentence).trim()).filter(Boolean)
        : splitTextToSentences(item?.text ?? "");
    const text = sentences.length > 1 ? joinSentencesWithParagraphBreak(sentences) : normalizeInlineNewlines(item?.text ?? sentences[0] ?? "");
    return {
        ...item,
        text,
        ...(sentences.length > 1 ? { sentences } : {}),
    };
}

export function syncJsonDataFromMedia(jsonData, media) {
    if (!jsonData?.scriptFiles || !media?.srt_data) return jsonData;
    const editableTracks = media.srt_data.filter((track) => !track.isImageTrack);
    return {
        ...jsonData,
        scriptFiles: jsonData.scriptFiles.map((scriptFile, index) => {
            const track = editableTracks.find((item) => item.id === index) ?? editableTracks[index];
            if (!track?.data) return scriptFile;
            const { inlineData, ...scriptFileWithoutText } = scriptFile;
            if (scriptFile.filePath) return scriptFileWithoutText;
            return {
                ...scriptFileWithoutText,
                inlineData: track.data.map(serializeJsonSrtItem),
            };
        }),
    };
}

function stripInlineDataFromVcJson(jsondata) {
    if (!jsondata?.scriptFiles) return jsondata;
    const { srtFiles, jsonFiles, ...restJsonData } = jsondata;
    return {
        ...restJsonData,
        scriptFiles: jsondata.scriptFiles.map((scriptFile) => {
            const { inlineData, ...rest } = scriptFile;
            return rest;
        }),
    };
}

async function tryGetFileFromPath(dirHandle, path) {
    try {
        return await getFileFromPath(dirHandle, path);
    } catch (err) {
        console.warn("ファイル読み込みスキップ:", path, err);
        return null;
    }
}

function makeTrack({ id, name, filePath = "", data = [], isImageTrack = false, defaultStyle = "default-style-1" }) {
    const normalizedData = normalizeSrtItems(cloneSrtData(data));
    return {
        id,
        name,
        file_path: filePath,
        height: 40,
        default_class: defaultStyle,
        isImageTrack,
        data: normalizedData,
    };
}

export async function getMedia(data,dirHandle) {
    if (!dirHandle || !data || data.name === "dummy") {
      return getDefaultMedia();
    }
    let audio = null;
    let audioUrl = null;
    let duration = 0;
    const audiofile = await tryGetFileFromPath(dirHandle, data.audioFilePath);
    if (audiofile) {
      audioUrl = URL.createObjectURL(audiofile);
      audio = new Audio(audioUrl);
      await new Promise((resolve) => {
        audio.onloadedmetadata = resolve;
        audio.onerror = resolve;
      });
      duration = Number.isFinite(audio.duration) ? audio.duration : 0;
      const initialSeek = data.seekTime ?? 0;
      audio.currentTime = duration ? Math.min(initialSeek, duration) : initialSeek;
    }

    const srtDatafiles = [];
    for (const [i, script] of (data.scriptFiles ?? []).entries()) {
      let srtData = cloneSrtData(script.inlineData);
      let srtName = script.name || script.filePath || `${data.name}-${i + 1}.srt`;
      if (!srtData.length && script.filePath) {
        const scriptFile = await tryGetFileFromPath(dirHandle, script.filePath);
        if (scriptFile) {
          srtName = scriptFile.name;
          const text = await scriptFile.text();
          try {
            srtData = script.filePath.toLowerCase().endsWith(".json")
              ? parseSentenceJsonSubtitle(text)
              : parseSrt(text);
          } catch (err) {
            console.warn("字幕ファイルの解析に失敗しました:", script.filePath, err);
            srtData = [];
          }
        }
      }
      extendLastClipToDuration(srtData, duration);
      srtDatafiles.push(makeTrack({
        id: i,
        name: srtName,
        filePath: script.filePath,
        data: srtData,
        defaultStyle: script.defaultStyle ?? script.default_class ?? "default-style-1",
      }));
    }

    if (!duration) duration = getDurationFromSrtData(srtDatafiles);

    let imageURL = null;
    let imagePath = null;
    if (data.imageSrtPath) {
      const imgSrtFile = await tryGetFileFromPath(dirHandle, data.imageSrtPath);
      if (imgSrtFile) {
        const imgSrtText = await imgSrtFile.text();
        const imgSrtparts = parseSrt(imgSrtText);
        extendLastClipToDuration(imgSrtparts, duration);
        srtDatafiles.push(makeTrack({
          id: srtDatafiles.length,
          name: imgSrtFile.name,
          filePath: data.imageSrtPath,
          data: imgSrtparts,
          isImageTrack: true,
        }));
        imagePath = imgSrtparts[0]?.text?.replace(/\\/g, "/") ?? null;
      }
    }
    if (!imagePath && data.imageFilePath) {
      imagePath = data.imageFilePath.replace(/\\/g, "/");
    }
    if (imagePath) {
      const imageFile = await tryGetFileFromPath(dirHandle, imagePath);
      if (imageFile) imageURL = URL.createObjectURL(imageFile);
    }

    return {
      name: data.name,
      audio,
      audioUrl,
      image_data: {
        currentId: 0,
        currentImage: imageURL,
        currentImagePath: imagePath,
        size: { x: 0, y: 0 },
      },
      srt_data: srtDatafiles,
      isAudio: !!audio,
      isPlaying: false,
      duration,
      playbackRate: 1,   // 呼び出し元で現在値に上書きされる
      volume: 0.5,       // 同上
    };
  }


