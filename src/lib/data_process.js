// スタイルの色をすべて正準形 #rrggbbaa に統一する（カラーピッカーが rgba() 文字列を
// 受け取って NaN 化する不具合を根本から断つ）。色を持つ全プロジェクトデータ生成口で適用する。
function normalizeStyleColors(styles) {
    if (!styles) return styles;
    for (const key of Object.keys(styles)) {
        const style = styles[key];
        if (!style) continue;
        if (typeof style.textColor === "string") style.textColor = COLOR.toHex8(style.textColor);
        for (const sub of ["outline1", "outline2", "shadow"]) {
            if (style[sub] && typeof style[sub].color === "string") {
                style[sub].color = COLOR.toHex8(style[sub].color);
            }
        }
    }
    return styles;
}

